"""Deploy the MCP server package into a project and generate the launcher.

MCP client configuration files have no ``cwd`` field and no way to set
``PYTHONPATH``, so pointing them at ``addons/godot_mcp/server.py`` would only
work for repositories. Instead the installer copies the real ``server`` package
to ``<project>/.godot-bridge-mcp/server`` and generates ``run_server.py`` next to
it: a self-contained entry point that fixes ``sys.path`` itself. Every client
can then start the bridge with a plain ``command`` + ``args`` pair.
"""

from __future__ import annotations

import shutil
from pathlib import Path
from typing import Any, Dict, Optional

from . import RUN_SERVER_NAME, RUNTIME_DIR_REL, SERVER_PACKAGE
from .sources import copy_tree, find_server_source

#: Content of the generated launcher (written verbatim, LF endings).
RUN_SERVER_TEMPLATE = '''#!/usr/bin/env python3
"""Launcher generated by the Godot Bridge MCP installer.

Any MCP client can start the bridge with a plain ``command``/``args`` pair::

    "<venv python>" "<project>/.godot-bridge-mcp/server/run_server.py"

No ``PYTHONPATH`` and no working-directory requirement: this file sits inside
the copied ``server`` package directory, so it puts the *parent* directory first
on ``sys.path`` and then imports :mod:`server.server`.
"""

import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)  # directory that contains the ``server`` package

# ``sys.path[0]`` is this file's directory, which also holds the package module
# ``server.py``; remove it so that ``import server`` always resolves the package.
sys.path[:] = [entry for entry in sys.path if os.path.abspath(entry or os.getcwd()) != _HERE]
sys.path.insert(0, _ROOT)

from server.server import main  # noqa: E402  (path setup must run first)

if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
'''


def deploy_server(project_dir: Path, source: Optional[Path] = None) -> Dict[str, Any]:
    """Copy the server package into ``project_dir`` and write ``run_server.py``.

    Args:
        project_dir: Already validated Godot project directory.
        source: Addon source directory, used to derive the repository layout.
    Returns:
        ``{"server_dir", "run_script", "server_source", "copied"}``
    Raises:
        InstallError: When the ``server`` package cannot be located.
    """
    server_source = find_server_source(source)
    runtime_root = Path(project_dir) / RUNTIME_DIR_REL
    runtime_root.mkdir(parents=True, exist_ok=True)
    target = runtime_root / SERVER_PACKAGE
    if target.exists():
        shutil.rmtree(str(target))
    copied = copy_tree(server_source, target)
    run_script = target / RUN_SERVER_NAME
    run_script.write_text(RUN_SERVER_TEMPLATE, encoding="utf-8", newline="\n")
    return {
        "server_dir": str(target),
        "run_script": str(run_script),
        "server_source": str(server_source),
        "copied": copied,
    }


__all__ = ["RUN_SERVER_TEMPLATE", "deploy_server"]
